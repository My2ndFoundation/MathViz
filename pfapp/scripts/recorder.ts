/**
 * bun scripts/recorder.ts [--target <t>]
 *
 * The maths shell's video recorder, taken from the web version's navigation shell (`../app.html`,
 * the "录制器" script block and its CSS) into `app/public/recorder/{rec.js,rec.css}` — generated,
 * never committed (.gitignore), so the web shell stays its only edit source (design §2: the web
 * version is the only content source). Only the maths app has a recorder: for any other target the
 * directory is removed, since `public/` ships whole (build-local STAGED).
 *
 * The block is taken verbatim but for one swap, each counted so that a change on the web side
 * fails the build loudly instead of shipping a recorder that half-works:
 *
 * - `document.querySelector('.stage')` / `('main.stage')` → `REC_HOST.stage()`: in the web shell
 *   the stage is the iframe's parent; here the iframe sits in `.rec-stage` beside the ask panel
 *   (components/recorder.tsx defines REC_HOST), and the shell's own `main.stage` holds both.
 * - CSS `.stage.rec-live` → `.rec-stage.rec-live` for the same reason.
 *
 * The block's other free names — `frame`, `curId`, `LANG`, `byId` — are the web shell's globals;
 * components/recorder.tsx defines them on window before loading rec.js.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const PFAPP = resolve(import.meta.dir, "..");
export const RECORDER_DIR = join(PFAPP, "app", "public", "recorder");
const APP_HTML = resolve(PFAPP, "..", "app.html");

const JS_START = "/* ================= 录制器 ================= */";
const JS_END = "/* ===== /REC:UI ===== */";
const CSS_START = "/* ===== 录制器 ===== */";
const CSS_END = "</style>";

function between(src: string, start: string, end: string, includeEnd: boolean): string {
  const a = src.indexOf(start);
  if (a < 0 || src.indexOf(start, a + 1) >= 0) {
    throw new Error(`app.html: expected exactly one "${start}"`);
  }
  const b = src.indexOf(end, a);
  if (b < 0) throw new Error(`app.html: no "${end}" after "${start}"`);
  return src.slice(a, includeEnd ? b + end.length : b);
}

function swap(text: string, from: string, to: string, count: number, what: string): string {
  const n = text.split(from).length - 1;
  if (n !== count) {
    throw new Error(
      `app.html recorder ${what}: expected ${count} × ${JSON.stringify(from)}, found ${n} — update scripts/recorder.ts`,
    );
  }
  return text.split(from).join(to);
}

/** The recorder's script and stylesheet, from the web shell's source. */
export function buildRecorder(appHtml: string): { js: string; css: string } {
  let js = between(appHtml, JS_START, JS_END, true);
  js = swap(js, "document.querySelector('.stage')", "REC_HOST.stage()", 2, "script");
  js = swap(js, "document.querySelector('main.stage')", "REC_HOST.stage()", 2, "script");
  let css = between(appHtml, CSS_START, CSS_END, false);
  css = swap(css, ".stage.rec-live", ".rec-stage.rec-live", 2, "styles");
  const head = (kind: string) =>
    `/* Generated by pfapp/scripts/recorder.ts from MathViz app.html (the ${kind} of its recorder). Do not edit. */\n`;
  return { js: `${head("script")}'use strict';\n${js}\n`, css: `${head("styles")}${css}` };
}

/** Write (maths) or remove (any other target) app/public/recorder/. */
export function writeRecorder(target: string, dir: string = RECORDER_DIR): void {
  if (target !== "math") {
    if (existsSync(dir)) rmSync(dir, { recursive: true, force: true });
    // and public/ itself when nothing else is in it: build-local stages it whenever it exists
    const parent = dirname(dir);
    if (existsSync(parent) && readdirSync(parent).length === 0) rmSync(parent, { recursive: true });
    return;
  }
  const { js, css } = buildRecorder(readFileSync(APP_HTML, "utf8"));
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "rec.js"), js);
  writeFileSync(join(dir, "rec.css"), css);
}

if (import.meta.main) {
  const i = process.argv.indexOf("--target");
  const target = (i >= 0 ? process.argv[i + 1] : process.env.MATHVIZ_TARGET) ?? "math";
  writeRecorder(target);
  console.log(target === "math" ? `recorder → ${RECORDER_DIR}` : `no recorder for ${target}`);
}
